"""
Напишіть функцію, яка
 приймає іменовані аргументи для ширини та висоти прямокутника та
обчислює його площу;
 приймає ім'я та вік користувача як іменовані аргументи та повертає
рядок з вітанням;
 приймає два числа і повертає їх добуток. Функція повинна мати один
позиційний аргумент і один іменований аргумент;
 обчислює середнє арифметичне чисел у списку, переданих як
позиційний аргумент;
 додає два числа, передані як позиційні аргументи.
 приймає іменований аргумент divider та список чисел numbers, і
повертає список чисел, які діляться на divider;
"""


# площа прямокутника
def rectangle_area(*, width, height):
    """обчислює площу прямокутника за шириною та висотою."""
    return width * height


# вітання користувача
def greet(*, name, age):
    """повертає рядок-вітання з іменем та віком."""
    return f"привіт, {name}! тобі {age} років."


# добуток двох чисел (один позиційний, один іменований)
def multiply(a, *, b):
    """повертає добуток позиційного аргументу a та іменованого b."""
    return a * b


#  середнє арифметичне списку
def average(numbers):
    """обчислює середнє арифметичне елементів списку."""
    if not numbers:
        return 0
    return sum(numbers) / len(numbers)


#  сума двох позиційних аргументів
def add(a, b):
    """повертає суму двох чисел."""
    return a + b


# числа, що діляться на divider
def divisible(*, divider, numbers):
    """повертає список чисел зі списку numbers, що діляться на divider."""
    result = []
    for n in numbers:
        if n % divider == 0:
            result.append(n)
    return result


# демонстрація

# введення даних для площі прямокутника
width = float(input("введіть ширину прямокутника: "))
height = float(input("введіть висоту прямокутника: "))
print("площа прямокутника:", rectangle_area(width=width, height=height))

# введення імені та віку для вітання
name = input("\nвведіть ваше ім'я: ")
age = int(input("введіть ваш вік: "))
print(greet(name=name, age=age))

# введення двох чисел для добутку
a = float(input("\nвведіть перше число (позиційний аргумент): "))
b = float(input("введіть друге число (іменований аргумент b): "))
print("добуток:", multiply(a, b=b))

# введення списку чисел для середнього
raw = input("\nвведіть числа через пробіл для середнього: ")
nums = [float(x) for x in raw.split()]
print("середнє арифметичне:", average(nums))

# введення двох чисел для суми
x = float(input("\nвведіть перше число для суми: "))
y = float(input("введіть друге число для суми: "))
print("сума:", add(x, y))

# введення дільника та списку чисел
divider = int(input("\nвведіть дільник: "))
raw2 = input("введіть числа через пробіл: ")
numbers = [int(x) for x in raw2.split()]
print(f"числа, що діляться на {divider}:", divisible(divider=divider, numbers=numbers))
