"""
З клавіатури вводиться дійсне число]3,5.0[x та ціле число10n
(вводяться з клавіатури). Розрахувати суму:
x - x²/2 + x³/3 - ... + (-1)^(n-1) * x^n / n
Якщо різниця між сусідніми доданками буде менше 0.01, припинити
обчислення суми та вивести результат суми та значення параметруn
"""

# введення значень з клавіатури
x = float(input("введіть дійсне число x ∈ [0.5, 3]: "))
n = int(input("введіть ціле число n: "))

# перевірка діапазону x
if not (0.5 <= x <= 3):
    print("помилка: x має бути в діапазоні [0.5, 3]")
else:
    total = 0
    prev_term = None

    for i in range(1, n + 1):
        # обчислення поточного доданку ряду
        term = ((-1) ** (i - 1)) * (x ** i) / i

        # перевірка різниці між сусідніми доданками
        if prev_term is not None and abs(term - prev_term) < 0.01:
            print(f"різниця між доданками менше 0.01, зупинка на n = {i}")
            break

        total += term
        prev_term = term
    else:
        # цикл завершився без переривання
        i = n

    print(f"сума ряду: {total:.6f}")
    print(f"значення параметру n: {i}")