"""
завдання 2:
для масиву d (розмірності 12, випадкові цілі числа з [0, 10)):
 - поміняти місцями 1-й та останній елементи;
 - змінити порядок елементів на зворотній;
 - вивести елементи з непарними індексами, починаючи з кінця;
 - поміняти знак перших 4-х елементів на зворотний;
 - змінити форму на: а) 3*4; б) 2*6; в) 2*3*2.
"""
 
import numpy as np
 
# початковий масив
np.random.seed(42)
d = np.random.randint(0, 10, size=12)
print("початковий масив d:", d)
 
# перестановка 1-го та останнього елементів 
d_swap = d.copy()
d_swap[0], d_swap[-1] = d_swap[-1], d_swap[0]
print("\n1-й та останній поміняні:", d_swap)
 
d_rev = d[::-1]
print("зворотній порядок:", d_rev)
 
# непарні індекси: 1, 3, 5, 7, 9, 11 — беремо зрізом з кінця
d_odd = d[-1::-2]
print("непарні індекси з кінця:", d_odd)
 
# зміна знаку перших 4-х елементів 
d_neg = d.copy()
d_neg[:4] = -d_neg[:4]
print("знак перших 4 елементів змінено:", d_neg)
 
#зміна форми масиву 
print("\nформа 3x4:\n", d.reshape(3, 4))
print("\nформа 2x6:\n", d.reshape(2, 6))
print("\nформа 2x3x2:\n", d.reshape(2, 3, 2))
