"""
завдання 3:
створити масиви:
 - матрицю A розмірності 5*5, заповнену 0-ми та з елементами 1,2,3,4 під головною діагоналлю;
 - одиничну матрицю розмірності 3*3;
 - матрицю з одиниць розміру 4*5;
 - матрицю розмірністю 5*5, заповнену цілими числами від 0 до 4:
   а) по рядках; б) по стовпцях;
 - без циклів поміняти в матриці A місцями: 1-й та 2-й рядки,
   2-й та останній стовпці.
"""
 
import numpy as np
 
# матриця A 5*5: нулі та елементи 1,2,3,4 під головною діагоналлю
A = np.zeros((5, 5), dtype=int)
# np.diag з k=-1 задає субдіагональ
np.fill_diagonal(A[1:], [1, 2, 3, 4])
print("матриця A (5x5):\n", A)
 
# одинична матриця 3*3
identity = np.eye(3, dtype=int)
print("\nодинична матриця (3x3):\n", identity)
 
# матриця з одиниць 4*5
ones = np.ones((4, 5), dtype=int)
print("\nматриця з одиниць (4x5):\n", ones)
 
# матриця 5*5 з числами від 0 до 4 по рядках
# arange(25).reshape дає числа 0..24; беремо % 5 щоб отримати 0..4
row_fill = np.arange(25).reshape(5, 5) % 5
print("\nматриця 5x5 заповнена по рядках (0..4):\n", row_fill)
 
# матриця 5*5 з числами від 0 до 4 по стовпцях (транспонуємо row_fill)
col_fill = row_fill.T
print("\nматриця 5x5 заповнена по стовпцях (0..4):\n", col_fill)
 
A_mod = A.copy()
# міняємо місцями 1-й (індекс 0) та 2-й (індекс 1) рядки
A_mod[[0, 1]] = A_mod[[1, 0]]
# міняємо місцями 2-й (індекс 1) та останній (індекс 4) стовпці
A_mod[:, [1, 4]] = A_mod[:, [4, 1]]
print("\nматриця A після перестановки рядків і стовпців:\n", A_mod)
