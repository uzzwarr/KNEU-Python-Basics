"""
завдання 1:
створити наступні одновимірні масиви:
 - a розмірності 10, заповнений послідовністю цілих чисел від 0 до 9;
 - b розмірності 10 із рівномірно розподіленими значеннями від 0 до 1,
   не включаючи ні 0, ні 1;
 - c розмірності 10, заповнений рівномірно розподіленими випадковими
   числами зі стандартного нормального розподілу;
 - d масив розмірності 12 випадкових цілих чисел з інтервалу [0; 10);
 - випадковий вектор-рядок розмірності 1*10 та знайти середнє значення
   його елементів.
"""
 
import numpy as np
 
# масив цілих чисел від 0 до 9
a = np.arange(10)
print("масив a:", a)
 
# рівномірно розподілені значення від 0 до 1 (без крайніх точок)
b = np.linspace(0, 1, 12, endpoint=False)[1:11]
print("масив b:", b)
 
# випадкові числа зі стандартного нормального розподілу
c = np.random.randn(10)
print("масив c:", np.round(c, 4))
 
# випадкові цілі числа з інтервалу [0, 10)
d = np.random.randint(0, 10, size=12)
print("масив d:", d)
 
# вектор-рядок розмірності 1*10 та його середнє
row_vector = np.random.randint(0, 10, size=(1, 10))
print("\nвектор-рядок (1x10):", row_vector)
print("середнє значення вектора:", round(row_vector.mean(), 4))
