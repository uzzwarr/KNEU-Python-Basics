"""

Згенерувати два списки цілих випадкових цілих чисел: list_1 з 8
елементів із діапазону [-3, 5], та list_2 з 10 елементів з діапазону [2, 10]. На їх
основі
 на основі списку list_1 створіть кортеж tuple_1, в якому від’ємні
елементи замінити їх абсолютними значеннями;
 створить список чисел, присутніх в обох списках;
 кортеж, що об’єднує числа, що присутні в обох списках, без дублікатів;
 список чисел, наявних у списку list_2 та відсутніх у list_1;
 кортеж парних чисел, які присутні в обох списках;
 список чисел, що наявні у list_1 та відсутні у list_2, які більше 3

"""

import random

# генерація двох списків випадкових чисел
list_1 = [random.randint(-3, 5) for _ in range(8)]
list_2 = [random.randint(2, 10) for _ in range(10)]

print("list_1:", list_1)
print("list_2:", list_2)

# кортеж, де від'ємні елементи замінені абсолютними значеннями
tuple_1 = tuple(abs(x) if x < 0 else x for x in list_1)
print("\ntuple_1 (абсолютні значення):", tuple_1)

# список чисел, присутніх в обох списках (перетин)
common_list = list(set(list_1) & set(list_2))
print("спільні числа:", common_list)

# кортеж, що об'єднує всі числа з обох списків без дублікатів (об'єднання)
union_tuple = tuple(set(list_1) | set(list_2))
print("об'єднання без дублікатів:", union_tuple)

# список чисел у list_2, яких немає у list_1 (різниця)
only_in_list_2 = list(set(list_2) - set(list_1))
print("є в list_2, але немає в list_1:", only_in_list_2)

# кортеж парних чисел, які присутні в обох списках
even_common_tuple = tuple(x for x in set(list_1) & set(list_2) if x % 2 == 0)
print("спільні парні числа:", even_common_tuple)

# список чисел, що є у list_1, відсутні у list_2, і більше 3
list_1_gt_3_not_in_2 = list(x for x in set(list_1) - set(list_2) if x > 3)
print("в list_1, немає в list_2, більше 3:", list_1_gt_3_not_in_2)