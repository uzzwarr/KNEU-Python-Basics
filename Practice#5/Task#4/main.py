"""

Дано два словники, в яких ключами є малі букви латинського алфавіту,
а значеннями - цілі числа. В першому словнику можуть зустрічатися ключі
чи значення, які присутні в другому словнику, або навпаки. Наприклад, вміст
словників може бути наступний: a = {'x' : 1, 'y' : 2, 'z' : 3}, b =
{'w' : 10, 'x' : 11, 'y' : 2}
 надрукуйте спільні пари «ключ-значення» для обох словників у
форматі як у вихідних даних;
 надрукуйте ключі, які присутні в першому словнику, але яких немає в
другому, в одному рядку через пропуск;
 об’єднайте ці два словники в один

"""

a = {'x': 1, 'y': 2, 'z': 3}
b = {'w': 10, 'x': 11, 'y': 2}

print("спільні пари «ключ-значення»:")
# шукаємо ключі, які є в обох словниках і значення яких співпадають
for k in a:
    if k in b and a[k] == b[k]:
        print(f"'{k}' : {a[k]}")

print("\nключі, які є в 'a', але немає в 'b':")
# виводимо ключі через пропуск
keys_only_in_a = [k for k in a if k not in b]
print(*keys_only_in_a)

print("\nоб'єднаний словник:")
# об'єднання словників (значення з 'b' перезапишуть значення з 'a' при конфлікті ключів)
merged_dict = {**a, **b}
print(merged_dict)