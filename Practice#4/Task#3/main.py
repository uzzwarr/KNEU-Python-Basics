"""
Сформувати список з list_3, що складається з елементів списку list_2 та
елементів рядку “A b Bd 12a057cdF#”.
 додати в list_3 елемент „@‟ після елементу “B” в кінець списку;
 видалити 3-й та останній елементи списку;
 знайти кількість входжень елементу 0;
 знайти індекси першого входження елементу 0;
 перетворити список list_3 на рядок із розподільником “, ”;

"""

import random

list_2 = [random.randint(-7, 7) for _ in range(10)]

# формування list_3 (об'єднання list_2 та символів рядка)
string_data = "A b Bd 12a057cdF#"
list_3 = list_2 + list(string_data)
print("початковий list_3:", list_3)

# додаємо '@' після елементу 'B' та в кінець списку
if 'B' in list_3:
    idx_b = list_3.index('B')
    list_3.insert(idx_b + 1, '@')
list_3.append('@')
print("після додавання '@':", list_3)

# видалення 3-го та останнього (індекс -1) елементів
del list_3[2]
del list_3[-1]
print("після видалення елементів:", list_3)

# знаходження кількості входжень елемента 0
count_zero = list_3.count(0) + list_3.count('0')
print("кількість входжень 0 та '0':", count_zero)

# знаходження індексу першого входження 0 або '0'
first_zero_idx = -1
for i, val in enumerate(list_3):
    if val == 0 or val == '0':
        first_zero_idx = i
        break
print("індекс першого входження 0:", first_zero_idx)

# перетворення списку на рядок із роздільником ", "
# перетворюємо всі елементи на рядки перед об'єднанням
string_list_3 = ", ".join(map(str, list_3))
print("рядок зі списку:", string_list_3)