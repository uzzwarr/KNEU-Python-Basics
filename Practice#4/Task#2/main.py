"""
Сформувати список list_2 із 10 випадкових цілих чисел із діапазону [-
7,7] із використанням бібліотеки random. Виконати такі дії
 вивести мінімальний та максимальний елементи списку;
 знайти довжину списку та суму його елементів;
 знайти індекси мінімального та максимального елементів;
 поміняти місцями максимальний та мінімальний елементи;
 вивести відсортовану копію списку

"""

import random

# формуємо список із 10 випадкових цілих чисел у діапазоні [-7, 7]
list_2 = [random.randint(-7, 7) for _ in range(10)]
print(f"\nпочатковий list_2: {list_2}")

# мінімальний та максимальний елементи
min_val = min(list_2)
max_val = max(list_2)
print(f"мінімальний: {min_val}, максимальний: {max_val}")

# довжина списку та сума його елементів
list_len = len(list_2)
list_sum = sum(list_2)
print(f"довжина: {list_len}, сума: {list_sum}")

# індекси мінімального та максимального елементів
min_idx = list_2.index(min_val)
max_idx = list_2.index(max_val)
print(f"індекс мінімального: {min_idx}, індекс максимального: {max_idx}")

# міняємо місцями максимальний та мінімальний елементи
list_2[min_idx], list_2[max_idx] = list_2[max_idx], list_2[min_idx]
print(f"після обміну min та max: {list_2}")

# відсортована копія списку (не змінюючи оригінал)
sorted_list_2 = sorted(list_2)
print(f"відсортована копія: {sorted_list_2}")