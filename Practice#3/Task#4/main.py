"""
Для рядка із п. 3:
 видалити пробіли на початку та наприкінці рядка;
 зробити початок усіх слів із заголовної (великої літери);
 підрахувати, скільки разів в рядок входить артикль “a”;
 знайти індекс першого входження артиклю “a”;
 замінити артикль “a” на займенник “any” тільки у другому реченні;
 Розділити цей рядок на два за розподільником знак оклику.
"""

# беремо рядок з попереднього завдання
quote = " Don't worry, it's a piece of cake, there will be no problem! Choose a job you love, and you will never have to work a day in your life!!! "

# видалити пробіли на початку та наприкінці
stripped_quote = quote.strip()
print(f"Без зайвих пробілів: '{stripped_quote}'")

# зробити початок усіх слів із заголовної літери
title_quote = stripped_quote.title()
print(f"Кожне слово з великої: '{title_quote}'")

# підрахувати, скільки разів в рядок входить артикль “a”
# (рахуємо як окреме слово з пробілами, щоб не порахувати 'a' у слові 'cake')
count_a = stripped_quote.count(" a ")
print(f"Кількість артиклів 'a': {count_a}")

# знайти індекс першого входження артиклю “a”
# Шукаємо ' a ', щоб не знайти літеру всередині інших слів
index_a = stripped_quote.find(" a ")
print(f"Індекс першого входження 'a': {index_a}")

# замінити артикль “a” на “any” ТІЛЬКИ у другому реченні
sentences = stripped_quote.split("!", 1)
# робимо заміну у другій частині (додаємо пробіли, щоб міняти саме слово)
sentences[1] = sentences[1].replace(" a ", " any ")
# з'єднуємо назад
replaced_quote = "!".join(sentences)
print(f"Заміна 'a' на 'any' в другому реченні:\n{replaced_quote}")

# розділити цей рядок на два за розподільником знак оклику
split_quote = stripped_quote.split("!", 1)
print(f"Розділено на два рядки:\nЧастина 1: {split_quote[0]}\nЧастина 2: {split_quote[1]}")